import type {
  StoryChoice,
  StoryCondition,
  StoryGraph,
  StoryMedia,
  StoryNode,
  VariableChange,
} from "@/shared/story-contract";

const root = "/story-assets/after-school-wind/";

const picture = (filename: string, alt: string): StoryMedia => ({
  kind: "image",
  role: "scene",
  url: `${root}${encodeURIComponent(filename)}`,
  alt,
});

const media = (...items: Array<[filename: string, alt: string]>): StoryMedia[] =>
  items.map(([filename, alt]) => picture(filename, alt));

const add = (key: string, value: number): VariableChange => ({
  key,
  operation: "add",
  value,
});

const setFlag = (key: string, value = true): VariableChange => ({
  key,
  operation: "set",
  value,
});

const choice = (
  id: string,
  label: string,
  targetNodeId: string,
  changes: VariableChange[] = [],
  feedback?: string,
  conditions?: StoryCondition[],
): StoryChoice => ({
  id,
  label,
  targetNodeId,
  changes,
  feedback,
  conditions,
  importance: "key",
});

const scene = (
  id: string,
  title: string,
  content: string,
  images: StoryMedia[],
  choices?: StoryChoice[],
): StoryNode => ({
  id,
  type: "scene",
  title,
  speaker: "我",
  content,
  media: images,
  choices,
  presentation: { transition: "dissolve", textReveal: "paragraph" },
});

const passage = (
  id: string,
  title: string,
  content: string,
  images: StoryMedia[],
  nextNodeId: string,
  speaker = "我",
): StoryNode => ({
  id,
  type: "scene",
  title,
  speaker,
  content,
  media: images,
  nextNodeId,
  presentation: { transition: "dissolve", textReveal: "paragraph" },
});

const chapter = (
  id: string,
  title: string,
  content: string,
  filename: string,
  nextNodeId: string,
): StoryNode =>
  passage(
    id,
    title,
    content,
    media([filename, `${title}的校园景象`]),
    nextNodeId,
    "章节",
  );

const ending = (
  id: string,
  title: string,
  content: string,
  filename: string,
): StoryNode => ({
  id,
  type: "ending",
  endingKey: id,
  title,
  speaker: "我",
  content,
  media: media([filename, `${title}的结局画面`]),
  presentation: { transition: "dissolve", textReveal: "paragraph" },
});

